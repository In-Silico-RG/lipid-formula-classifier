#!/usr/bin/env python
"""
55_exclude_audited.py — Removes from the non-lipid layer the formulas of known lipid classes.

Applies the audit of 54_audit_nonlipids.py: every formula labelled non_lipid in master.parquet
that coincides with the formula of a common lipid class (generated by sum composition; SQDG,
MGDG, DGDG, DGTS/DGTA, DG, PC, PE, Cer …) is relabelled "discarded", so it is used neither as a
lipid nor as a non-lipid example (the same treatment as other formulas excluded by
01_normalize.py). The file before the change is kept as master_before_audit.parquet, and the
script refuses to run twice. Run after 01_normalize.py; only task B (lipid or not) depends on it.

Usage:  python 55_exclude_audited.py
Output: data/master.parquet (updated), data/master_before_audit.parquet, results/55_exclude_audited.log
"""
import shutil

import pandas as pd

import merged_common as mc  # noqa: E402

a54 = mc._load("a54", "54_audit_nonlipids.py")


def main():
    log = mc.logger("55_exclude_audited")
    src, backup = mc.DATOS / "master.parquet", mc.DATOS / "master_before_audit.parquet"
    if backup.exists():
        raise SystemExit("master_before_audit.parquet exists: the exclusion was already applied")
    m = pd.read_parquet(src)
    gen = a54.generate()
    hit = (m.label == "non_lipid") & m.formula.isin(gen.keys())
    before = m.label.value_counts().to_dict()
    shutil.copy2(src, backup)
    m.loc[hit, "label"] = "discarded"
    m.to_parquet(src, index=False)
    after = m.label.value_counts().to_dict()
    log("55 — NON-LIPID FORMULAS OF KNOWN LIPID CLASSES RELABELLED 'discarded'")
    log(f"  relabelled: {int(hit.sum()):,} formulas (generated classes: {len(gen):,} formulas, see 54_audit_nonlipids)")
    for lab in ("lipid", "non_lipid", "discarded"):
        log(f"  {lab:10s} {before.get(lab, 0):7,} -> {after.get(lab, 0):7,}")
    log(f"  backup: {backup.name}")


if __name__ == "__main__":
    main()
