#!/usr/bin/env python
"""
46_adversarial.py — Merged pipeline: artificial non-lipids and the shifted-mass test (§2.9).

The artificial formulas are generated by generar_n4() of 15_phase6_adversarial.py (same lipid
order, same known-formula exclusion), so the parent lipid of each artificial formula is known;
the script first checks that it reproduces data/n4_adversarial.csv exactly.

Four experiments with the final model on task B (lipid vs non-lipid, unit = formula):
  N1-N3            ordinary non-lipids only
  +N4b             plus the shifted-mass set
  +N4b+N4a(same n) plus a random sample of the perturbation set of the size of N4b
  +N4a+N4b         plus both artificial sets in full
Protocol: the master formulas follow the 5-fold split grouped by formula (merged_common); the
artificial formulas are divided into 5 folds BY PARENT LIPID, and fold k of both is the test
part of round k, so the model is never judged on an artificial formula whose parent it saw.
Seeds 0, 1, 2. Reported: sensitivity on test lipids, fraction of test N4a / N4b called lipid,
and the ratio (fraction of N4b called lipid) / sensitivity (1 = no discrimination).

Usage:  python 46_adversarial.py --set=R2C --model=XGB
Output: results/46_adversarial_<set>_<model>.log + .csv
"""
import sys
import warnings

import numpy as np
import pandas as pd
from sklearn.model_selection import GroupKFold

warnings.filterwarnings("ignore")
import merged_common as mc  # noqa: E402

OPT = dict(a[2:].split("=", 1) for a in sys.argv[1:] if a.startswith("--") and "=" in a)
SET, MODEL = OPT["set"], OPT["model"]
m15 = mc._load("m15", "15_phase6_adversarial.py")


def make(seed, y):
    import xgboost as xgb
    from sklearn.ensemble import RandomForestClassifier
    from sklearn.utils.class_weight import compute_sample_weight
    J = int(OPT.get("jobs", 8))
    if MODEL.startswith("RF"):
        return RandomForestClassifier(n_estimators=500, n_jobs=J, random_state=seed,
                                      class_weight="balanced" if MODEL == "RF-weighted" else None), {}
    return (xgb.XGBClassifier(n_estimators=500, tree_method="hist", n_jobs=J, verbosity=0, random_state=seed),
            {"sample_weight": compute_sample_weight("balanced", y)} if MODEL == "XGB-weighted" else {})


def main():
    log = mc.logger(f"46_adversarial_{SET}_{MODEL}")
    log("=" * 88)
    log(f"46 — ARTIFICIAL NON-LIPIDS · input list {SET} · model {MODEL}")
    log("=" * 88)
    m, y, _ = mc.load_detection()
    master = pd.read_parquet(mc.DATOS / "master.parquet")
    known = set(master.formula)
    mbk = pd.read_csv(mc.DATOS / "spectra" / "formulas_massbank.csv")
    ext = pd.read_csv(mc.DATOS / "spectra" / "formulas_experimental.csv").fillna("")
    known |= set(mbk.formula) | set(ext.formula)
    z = np.load(mc.DATOS / "representations.npz", allow_pickle=True)
    lip = [f for f, e in zip(z["formula"], z["label"]) if e == "lipid"]
    n4a, pa, n4b, pb = m15.generar_n4(lip, known, log=lambda s: None)
    refp = mc.DATOS / "n4_adversarial.csv"
    if refp.exists():
        ref = pd.read_csv(refp)
        lay = ref.columns[1]
        same = set(ref.formula[ref[lay] == "N4a"]) == set(n4a) and set(ref.formula[ref[lay] == "N4b"]) == set(n4b)
        log(f"N4a {len(n4a):,}, N4b {len(n4b):,}; identical to data/n4_adversarial.csv: {same}")
        if not same:
            raise SystemExit("generation does not reproduce n4_adversarial.csv: stop")
    else:
        log(f"N4a {len(n4a):,}, N4b {len(n4b):,}; data/n4_adversarial.csv absent, comparison skipped")

    X = mc.features(m.formula.tolist(), sets=[SET])[SET]
    Xa = mc.features(n4a, sets=[SET])[SET]
    Xb = mc.features(n4b, sets=[SET])[SET]
    ga, gb = np.array([pa[f] for f in n4a]), np.array([pb[f] for f in n4b])
    groups = m.formula.to_numpy()

    rows = []
    for scen in ("N1-N3", "+N4b", "+N4b+N4a(same n)", "+N4a+N4b"):
        per = []
        for s in mc.SEEDS:
            rng = np.random.default_rng(s)
            fa = np.empty(len(n4a), int)
            fb = np.empty(len(n4b), int)
            # parents shuffled per seed, then 5 groups of parents
            for arr, g, out in ((Xa, ga, fa), (Xb, gb, fb)):
                up = rng.permutation(np.unique(g))
                fold_of = {p: i % mc.N_FOLDS for i, p in enumerate(up)}
                out[:] = [fold_of[p] for p in g]
            sens, ca, cb = [], [], []
            for k, (tr, te) in enumerate(mc.splits(y, groups, s)):
                Xtr, ytr = [X[tr]], [y[tr]]
                atr, btr = fa != k, fb != k
                if scen in ("+N4b", "+N4b+N4a(same n)", "+N4a+N4b"):
                    Xtr.append(Xb[btr]); ytr.append(np.zeros(btr.sum(), int))
                if scen == "+N4a+N4b":
                    Xtr.append(Xa[atr]); ytr.append(np.zeros(atr.sum(), int))
                if scen == "+N4b+N4a(same n)":
                    idx = rng.choice(np.where(atr)[0], size=min(btr.sum(), atr.sum()), replace=False)
                    Xtr.append(Xa[idx]); ytr.append(np.zeros(len(idx), int))
                Xtr, ytr = np.vstack(Xtr), np.concatenate(ytr)
                mdl, kw = make(s, ytr)
                mdl.fit(Xtr, ytr, **kw)
                pt = mdl.predict(X[te])
                lip_te = y[te] == 1
                sens.append(((pt == 1) & lip_te).sum() / lip_te.sum())
                ca.append(mdl.predict(Xa[fa == k]).mean())
                cb.append(mdl.predict(Xb[fb == k]).mean())
            S, A, B = np.mean(sens) * 100, np.mean(ca) * 100, np.mean(cb) * 100
            per.append({"sensitivity": S, "N4a_called_lipid": A, "N4b_called_lipid": B, "ratio_N4b": B / S})
        ms = mc.mean_sd(per)
        row = {"scenario": scen}
        for kk, (mu, sd) in ms.items():
            row[kk], row[kk + "_sd"] = mu, sd
        rows.append(row)
        log(f"  {scen:18s} sensitivity {ms['sensitivity'][0]:6.2f} ± {ms['sensitivity'][1]:.2f}   "
            f"N4a called lipid {ms['N4a_called_lipid'][0]:6.2f}   N4b called lipid {ms['N4b_called_lipid'][0]:6.3f}   "
            f"ratio {ms['ratio_N4b'][0]:.4f}")
    pd.DataFrame(rows).to_csv(mc.RES / f"46_adversarial_{SET}_{MODEL}.csv", index=False)
    log(f"\n  Saved: results/46_adversarial_{SET}_{MODEL}.csv")


if __name__ == "__main__":
    main()
